#!/usr/bin/env python3
"""Closed, source-immutable adapter for the Mesa 26 generators.

The transpiler supplies only capability-audited modes and arguments. Every
named-file generator works in a private build-tree staging directory; fetched
source trees are never output locations.

This module is self-contained. The legacy Mesa 20.0.8 entry point,
mesa20_generate.py, imports it and adds the two modes only Mesa 20 lanes use.
"""

from __future__ import annotations

from collections.abc import Callable, Mapping
import hashlib
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

# A mode handler receives the source root, the audited generator input, the
# final output path, the mode arguments and a private staging directory, and
# returns the generated bytes.
Handler = Callable[[Path, Path, Path, "list[str]", Path], bytes]


def fail(message: str) -> "NoReturn":
    program = Path(sys.argv[0]).name if sys.argv and sys.argv[0] else "mesa26_generate.py"
    raise SystemExit(f"{program}: {message}")


def child_path(root: Path, raw: str, label: str, *, must_exist: bool) -> Path:
    path = Path(raw).resolve()
    try:
        path.relative_to(root)
    except ValueError:
        fail(f"{label} escapes {root}: {path}")
    if path == root:
        fail(f"{label} must be a child of {root}")
    if must_exist and not path.is_file():
        fail(f"{label} is not a regular file: {path}")
    return path


def run(command: list[str], source_root: Path) -> bytes:
    environment = os.environ.copy()
    environment["PYTHONDONTWRITEBYTECODE"] = "1"
    result = subprocess.run(
        command,
        cwd=source_root,
        env=environment,
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if result.returncode != 0:
        sys.stderr.buffer.write(result.stderr)
        fail(f"generator exited with status {result.returncode}: {command[0]}")
    return result.stdout


def replace_once(arguments: list[str], marker: str, replacement: str) -> list[str]:
    count = sum(argument.count(marker) for argument in arguments)
    if count != 1:
        fail(f"mode requires exactly one {marker} marker, found {count}")
    return [argument.replace(marker, replacement) for argument in arguments]


def safe_basename(raw: str, label: str) -> str:
    path = Path(raw)
    if not raw or path.name != raw or raw in {".", ".."}:
        fail(f"unsafe {label}: {raw!r}")
    return raw


def python_stdout(
    source_root: Path, generator: Path, output: Path, arguments: list[str], work: Path
) -> bytes:
    if any(marker in argument for marker in ("@OUTPUT@", "@OUTDIR@") for argument in arguments):
        fail("python-stdout arguments contain an output marker")
    return run([sys.executable, "-B", str(generator), *arguments], source_root)


def python_output(
    source_root: Path, generator: Path, output: Path, arguments: list[str], work: Path
) -> bytes:
    staged = work / output.name
    command_arguments = replace_once(arguments, "@OUTPUT@", str(staged))
    run([sys.executable, "-B", str(generator), *command_arguments], source_root)
    if not staged.is_file():
        fail(f"Python generator did not create {staged.name}")
    return staged.read_bytes()


def python_dual_output(
    source_root: Path, generator: Path, output: Path, arguments: list[str], work: Path
) -> bytes:
    if len(arguments) < 2:
        fail("python-dual-output requires C and H output names")
    c_name = safe_basename(arguments[0], "generated C name")
    h_name = safe_basename(arguments[1], "generated header name")
    if c_name == h_name or output.name not in {c_name, h_name}:
        fail("python-dual-output target does not match its paired products")
    command_arguments = arguments[2:]
    if sum(arg.count("@OUT_C@") for arg in command_arguments) != 1 or sum(
        arg.count("@OUT_H@") for arg in command_arguments
    ) != 1:
        fail("python-dual-output requires one marker for each product")
    staged_c = work / c_name
    staged_h = work / h_name
    command_arguments = [
        arg.replace("@OUT_C@", str(staged_c)).replace("@OUT_H@", str(staged_h))
        for arg in command_arguments
    ]
    run([sys.executable, "-B", str(generator), *command_arguments], source_root)
    if not staged_c.is_file() or not staged_h.is_file():
        fail("Python generator did not create both paired products")
    return (work / output.name).read_bytes()


def flex(
    source_root: Path, generator: Path, output: Path, arguments: list[str], work: Path
) -> bytes:
    executable = os.environ.get("AROS_FLEX_EXECUTABLE", "")
    if not executable or not Path(executable).is_file():
        fail("AROS_FLEX_EXECUTABLE is missing or not a regular file")
    if any(argument.startswith("-o") or argument == "--stdout" for argument in arguments):
        fail("flex output options are owned by the adapter")
    return run([executable, *arguments, "--stdout", str(generator)], source_root)


def bison(
    source_root: Path, generator: Path, output: Path, arguments: list[str], work: Path
) -> bytes:
    if len(arguments) < 3:
        fail("bison mode requires SOURCE_NAME HEADER_NAME PREFIX")
    source_name = safe_basename(arguments[0], "Bison source name")
    header_name = safe_basename(arguments[1], "Bison header name")
    prefix = arguments[2]
    if not prefix or any(character.isspace() for character in prefix):
        fail(f"unsafe Bison prefix: {prefix!r}")
    extra = arguments[3:]
    if any(
        argument in {"-o", "--output", "-d", "--defines", "-l", "--no-lines"}
        or argument.startswith(("--output=", "--defines="))
        for argument in extra
    ):
        fail("Bison output and line controls are owned by the adapter")
    staged_source = work / source_name
    staged_header = work / header_name
    executable = os.environ.get("AROS_BISON_EXECUTABLE", "")
    if not executable or not Path(executable).is_file():
        fail("AROS_BISON_EXECUTABLE is missing or not a regular file")
    run(
        [
            executable,
            "-d",
            "-l",
            "-p",
            prefix,
            f"--defines={staged_header}",
            "-o",
            str(staged_source),
            *extra,
            str(generator),
        ],
        source_root,
    )
    if output.name == source_name:
        staged = staged_source
    elif output.name == header_name:
        staged = staged_header
    else:
        fail(f"Bison output {output.name} is neither {source_name} nor {header_name}")
    if not staged.is_file():
        fail(f"Bison did not create {staged.name}")
    data = staged.read_bytes()
    if output.name == header_name:
        # Bison derives the header guard from the absolute --defines
        # path. A temporary build-tree path would make two otherwise
        # identical Mesa builds differ byte-for-byte.
        match = re.search(rb"(?m)^#ifndef (YY_[A-Z0-9_]+_INCLUDED)$", data)
        if match is None or data.count(match.group(1)) != 3:
            fail("Bison header guard did not match the reviewed form")
        stable_name = re.sub(r"[^A-Z0-9]", "_", f"{prefix}_{header_name}".upper())
        stable_guard = f"AROS_MESA_{stable_name}_INCLUDED".encode("ascii")
        data = data.replace(match.group(1), stable_guard)
    return data


def mesa_git_sha1(
    source_root: Path, generator: Path, output: Path, arguments: list[str], work: Path
) -> bytes:
    if arguments:
        fail("mesa-git-sha1 mode accepts no arguments")
    return b'#define MESA_GIT_SHA1 ""\n'


def v3dx_wrapper(mode: str, versions: set[str], generator: Path, arguments: list[str]) -> bytes:
    if len(arguments) != 1 or arguments[0] not in versions:
        fail(f"{mode} mode requires exactly one of {sorted(versions)}")
    if not generator.name.startswith("v3dx_") or generator.suffix != ".c":
        fail(f"v3dx-wrapper input is not a v3dx C source: {generator.name}")
    version = arguments[0]
    return (f'#define V3D_VERSION {version}\n#include "{generator.name}"\n').encode("ascii")


def v3dx_wrapper26(
    source_root: Path, generator: Path, output: Path, arguments: list[str], work: Path
) -> bytes:
    return v3dx_wrapper("v3dx-wrapper26", {"42", "71"}, generator, arguments)


MODES: dict[str, Handler] = {
    "python-stdout": python_stdout,
    "python-output": python_output,
    "python-dual-output": python_dual_output,
    "flex": flex,
    "bison": bison,
    "mesa-git-sha1": mesa_git_sha1,
    "v3dx-wrapper26": v3dx_wrapper26,
}


def main(extra_modes: Mapping[str, Handler] | None = None) -> None:
    modes = dict(MODES)
    if extra_modes:
        modes.update(extra_modes)

    if len(sys.argv) < 6:
        fail(
            "usage: SOURCE_ROOT BUILD_ROOT GENERATOR_SCRIPT OUTPUT MODE "
            "[MODE_ARGUMENTS...]"
        )

    source_root = Path(sys.argv[1]).resolve()
    build_root = Path(sys.argv[2]).resolve()
    if not source_root.is_dir():
        fail(f"source root is not a directory: {source_root}")
    build_root.mkdir(parents=True, exist_ok=True)
    if not build_root.is_dir():
        fail(f"build root is not a directory: {build_root}")

    generator = child_path(
        source_root, sys.argv[3], "generator input", must_exist=True
    )
    output = child_path(build_root, sys.argv[4], "generator output", must_exist=False)
    mode = sys.argv[5]
    arguments = sys.argv[6:]

    work_parent = build_root / ".generator-work"
    work_parent.mkdir(parents=True, exist_ok=True)
    key = hashlib.sha256(str(output).encode("utf-8")).hexdigest()[:16]
    with tempfile.TemporaryDirectory(prefix=f"{key}-", dir=work_parent) as raw_work:
        handler = modes.get(mode)
        if handler is None:
            fail(f"unsupported generator mode: {mode!r}")
        data = handler(source_root, generator, output, arguments, Path(raw_work))

    if not data:
        fail(f"generator produced an empty result for {output.name}")
    sys.stdout.buffer.write(data)


if __name__ == "__main__":
    main()
