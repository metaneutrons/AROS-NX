struct wire_buffer {
    uint8_t bytes[512];
    size_t size;
    int ok;
};

static void wire_init(struct wire_buffer *buffer)
{
    memset(buffer, 0, sizeof *buffer);
    buffer->ok = 1;
}

static void wire_byte(struct wire_buffer *buffer, uint8_t value)
{
    if (!buffer->ok || buffer->size == sizeof buffer->bytes) {
        buffer->ok = 0;
        return;
    }
    buffer->bytes[buffer->size++] = value;
}

static void wire_varint(struct wire_buffer *buffer, uint64_t value)
{
    while (value >= 0x80u) {
        wire_byte(buffer, (uint8_t)((value & 0x7fu) | 0x80u));
        value >>= 7;
    }
    wire_byte(buffer, (uint8_t)value);
}

static void wire_key(struct wire_buffer *buffer, uint32_t field,
                     unsigned int wire_type)
{
    wire_varint(buffer, ((uint64_t)field << 3) | wire_type);
}

static void wire_uint_field(struct wire_buffer *buffer, uint32_t field,
                            uint32_t value)
{
    wire_key(buffer, field, 0u);
    wire_varint(buffer, value);
}

static void wire_bytes_field(struct wire_buffer *buffer, uint32_t field,
                             const uint8_t *bytes, size_t size)
{
    wire_key(buffer, field, 2u);
    wire_varint(buffer, (uint64_t)size);
    if (size > sizeof buffer->bytes - buffer->size ||
        (size != 0u && bytes == NULL)) {
        buffer->ok = 0;
        return;
    }
    if (size != 0u) {
        memcpy(buffer->bytes + buffer->size, bytes, size);
        buffer->size += size;
    }
}

static int make_item(struct p4_hosted_inbox_item *item, uint32_t event_id,
                     int32_t status,
                     const uint8_t ssid[P4_HOSTED_ASSOCIATION_SSID_SIZE],
                     uint32_t ssid_length,
                     const uint8_t bssid[P4_HOSTED_ASSOCIATION_BSSID_SIZE])
{
    struct wire_buffer data, wrapper, envelope;
    struct p4_hosted_rpc decoded;

    wire_init(&data);
    wire_bytes_field(&data, 1u, ssid, P4_HOSTED_ASSOCIATION_SSID_SIZE);
    wire_uint_field(&data, 2u, ssid_length);
    wire_bytes_field(&data, 3u, bssid, P4_HOSTED_ASSOCIATION_BSSID_SIZE);
    if (event_id == 775u) {
        wire_uint_field(&data, 4u, 11u);
        wire_uint_field(&data, 5u, 3u);
        wire_uint_field(&data, 6u, 7u);
    } else {
        wire_uint_field(&data, 4u, 8u);
        wire_uint_field(&data, 5u, 1u);
    }

    wire_init(&wrapper);
    wire_uint_field(&wrapper, 1u, (uint32_t)status);
    wire_bytes_field(&wrapper, 2u, data.bytes, data.size);
    wire_init(&envelope);
    wire_uint_field(&envelope, 1u, P4_HOSTED_RPC_TYPE_EVENT);
    wire_uint_field(&envelope, 2u, event_id);
    wire_bytes_field(&envelope, event_id, wrapper.bytes, wrapper.size);
    if (!data.ok || !wrapper.ok || !envelope.ok ||
        !p4_hosted_rpc_decode(envelope.bytes, envelope.size, &decoded) ||
        decoded.payload_size > sizeof item->payload)
        return 0;

    memset(item, 0, sizeof *item);
    item->msg_type = decoded.msg_type;
    item->msg_id = decoded.msg_id;
    item->uid = decoded.uid;
    item->payload_size = decoded.payload_size;
    if (decoded.payload_size != 0u)
        memcpy(item->payload, decoded.payload, decoded.payload_size);
    return 1;
}

static void make_malformed_item(struct p4_hosted_inbox_item *item,
                                uint32_t event_id)
{
    static const uint8_t malformed[] = { 0x12u, 0x02u, 0x0au, 0x00u };
    memset(item, 0, sizeof *item);
    item->msg_type = P4_HOSTED_RPC_TYPE_EVENT;
    item->msg_id = event_id;
    item->uid = 0u;
    item->payload_size = sizeof malformed;
    memcpy(item->payload, malformed, sizeof malformed);
}

static void fill_pattern(uint8_t *bytes, size_t size, uint8_t seed)
{
    size_t i;
    for (i = 0u; i < size; ++i)
        bytes[i] = (uint8_t)(seed + (uint8_t)(i * 17u));
}

static int bytes_are_zero(const void *memory, size_t size)
{
    const uint8_t *bytes = memory;
    size_t index;
    for (index = 0u; index < size; ++index)
        if (bytes[index] != 0u)
            return 0;
    return 1;
}

static void seed_resource_link(void)
{
    test_resource.associated = TRUE;
    test_resource.link_state = P4_WIFI_LINK_UP;
    memset(&test_resource.confirmed_ap, 0x5a,
           sizeof test_resource.confirmed_ap);
    memset(&test_resource.observed_ap, 0xa5,
           sizeof test_resource.observed_ap);
}

static void check_resource_link_invalidated(void)
{
    CHECK(test_resource.associated == FALSE);
    CHECK(test_resource.link_state == P4_WIFI_LINK_UNKNOWN);
    CHECK(bytes_are_zero(&test_resource.confirmed_ap,
                         sizeof test_resource.confirmed_ap));
    CHECK(bytes_are_zero(&test_resource.observed_ap,
                         sizeof test_resource.observed_ap));
}

static void check_callback_refusal_unchanged(
    struct wifi_probe_context *context,
    const struct p4_hosted_inbox_item *item)
{
    struct p4_hosted_link_observation before;
    struct p4_wifi_link_info confirmed_before, observed_before;
    ULONG link_state_before;
    uint32_t events_before = context->owner_events;
    uint32_t last_before = context->owner_last_event;
    memset(&test_resource, 0, sizeof test_resource);
    seed_resource_link();
    wifi_resource_base = &test_resource;
    memcpy(&confirmed_before, &test_resource.confirmed_ap,
           sizeof confirmed_before);
    memcpy(&observed_before, &test_resource.observed_ap,
           sizeof observed_before);
    link_state_before = test_resource.link_state;
    memcpy(&before, &context->link_observation, sizeof before);
    CHECK(!wifi_owner_event(context, item));
    CHECK(memcmp(&before, &context->link_observation, sizeof before) == 0);
    CHECK(context->owner_events == events_before);
    CHECK(context->owner_last_event == last_before);
    CHECK(test_resource.associated == TRUE);
    CHECK(test_resource.link_state == link_state_before);
    CHECK(memcmp(&confirmed_before, &test_resource.confirmed_ap,
                 sizeof confirmed_before) == 0);
    CHECK(memcmp(&observed_before, &test_resource.observed_ap,
                 sizeof observed_before) == 0);
    CHECK(test_resource.client_lock.depth == 0u);
}

static void test_callback_copies_775_and_accepts_776_down(void)
{
    struct wifi_probe_context context;
    struct p4_hosted_inbox_item item;
    uint8_t connected_ssid[P4_HOSTED_ASSOCIATION_SSID_SIZE];
    uint8_t disconnected_ssid[P4_HOSTED_ASSOCIATION_SSID_SIZE];
    uint8_t connected_bssid[P4_HOSTED_ASSOCIATION_BSSID_SIZE];
    uint8_t disconnected_bssid[P4_HOSTED_ASSOCIATION_BSSID_SIZE];

    memset(&context, 0, sizeof context);
    memset(&test_resource, 0, sizeof test_resource);
    seed_resource_link();
    wifi_resource_base = &test_resource;
    context.generation = 34u;
    CHECK(p4_hosted_link_init(&context.link_observation,
                              context.generation));
    fill_pattern(connected_ssid, sizeof connected_ssid, 0x21u);
    connected_ssid[0] = 0u;
    connected_ssid[29] = 0xffu;
    fill_pattern(disconnected_ssid, sizeof disconnected_ssid, 0x71u);
    fill_pattern(connected_bssid, sizeof connected_bssid, 0x31u);
    fill_pattern(disconnected_bssid, sizeof disconnected_bssid, 0x81u);

    memset(&context.link_snapshot, 0xa5, sizeof context.link_snapshot);
    context.link_query_revision = 77u;
    context.link_snapshot_matches_hint = TRUE;

    CHECK(make_item(&item, 775u, 0, connected_ssid, 32u,
                    connected_bssid));
    CHECK(wifi_owner_event(&context, &item) == 1);
    check_resource_link_invalidated();
    CHECK(test_resource.client_lock.depth == 0u);
    CHECK(bytes_are_zero(&context.link_snapshot,
                         sizeof context.link_snapshot));
    CHECK(context.link_snapshot_matches_hint == FALSE);
    CHECK(context.link_query_revision == 77u);
    CHECK(context.link_observation.kind == P4_HOSTED_LINK_UP_HINT);
    CHECK(context.link_observation.revision == 1u);
    CHECK(context.link_observation.ssid_length == 32u);
    CHECK(memcmp(context.link_observation.ssid, connected_ssid,
                 sizeof connected_ssid) == 0);
    CHECK(memcmp(context.link_observation.bssid, connected_bssid,
                 sizeof connected_bssid) == 0);
    CHECK(context.link_observation.channel == 11u);
    CHECK(context.link_observation.authmode == 3);
    CHECK(context.owner_events == 1u && context.owner_last_event == 775u);

    /* The inbox slot may be reused immediately after callback return. */
    memset(&item, 0xa5, sizeof item);
    CHECK(context.link_observation.ssid[0] == 0u);
    CHECK(context.link_observation.ssid[29] == 0xffu);
    CHECK(memcmp(context.link_observation.ssid, connected_ssid,
                 sizeof connected_ssid) == 0);
    CHECK(memcmp(context.link_observation.bssid, connected_bssid,
                 sizeof connected_bssid) == 0);

    memset(&context.link_snapshot, 0x5a, sizeof context.link_snapshot);
    context.link_snapshot_matches_hint = TRUE;
    CHECK(make_item(&item, 776u, 0, disconnected_ssid, 8u,
                    disconnected_bssid));
    seed_resource_link();
    CHECK(wifi_owner_event(&context, &item) == 1);
    check_resource_link_invalidated();
    CHECK(test_resource.client_lock.depth == 0u);
    CHECK(bytes_are_zero(&context.link_snapshot,
                         sizeof context.link_snapshot));
    CHECK(context.link_snapshot_matches_hint == FALSE);
    CHECK(context.link_query_revision == 77u);
    CHECK(context.link_observation.kind == P4_HOSTED_LINK_DOWN);
    CHECK(context.link_observation.revision == 2u);
    CHECK(context.link_observation.ssid_length == 8u);
    CHECK(memcmp(context.link_observation.ssid, disconnected_ssid,
                 sizeof disconnected_ssid) == 0);
    CHECK(memcmp(context.link_observation.bssid, disconnected_bssid,
                 sizeof disconnected_bssid) == 0);
    CHECK(context.link_observation.reason == 8u);
    CHECK(context.owner_events == 2u && context.owner_last_event == 776u);
}

static void test_malformed_and_bad_envelopes_are_transactional(void)
{
    struct wifi_probe_context context;
    struct p4_hosted_inbox_item item;
    uint8_t ssid[P4_HOSTED_ASSOCIATION_SSID_SIZE];
    uint8_t bssid[P4_HOSTED_ASSOCIATION_BSSID_SIZE];

    memset(&context, 0, sizeof context);
    memset(&test_resource, 0, sizeof test_resource);
    test_resource.associated = TRUE;
    wifi_resource_base = &test_resource;
    context.generation = 18u;
    CHECK(p4_hosted_link_init(&context.link_observation,
                              context.generation));
    fill_pattern(ssid, sizeof ssid, 0x14u);
    fill_pattern(bssid, sizeof bssid, 0x24u);
    CHECK(make_item(&item, 775u, 0, ssid, 32u, bssid));
    CHECK(wifi_owner_event(&context, &item) == 1);
    CHECK(test_resource.associated == FALSE);
    CHECK(context.owner_events == 1u);

    make_malformed_item(&item, 775u);
    check_callback_refusal_unchanged(&context, &item);
    make_malformed_item(&item, 776u);
    check_callback_refusal_unchanged(&context, &item);

    CHECK(make_item(&item, 775u, 0, ssid, 32u, bssid));
    item.msg_type = P4_HOSTED_RPC_TYPE_RESPONSE;
    check_callback_refusal_unchanged(&context, &item);
    CHECK(make_item(&item, 776u, 0, ssid, 32u, bssid));
    item.uid = 12u;
    check_callback_refusal_unchanged(&context, &item);
    CHECK(!wifi_owner_event(&context, NULL));
    CHECK(context.owner_events == 1u);
}

static void test_stale_generation_and_unrelated_metadata(void)
{
    struct wifi_probe_context context;
    struct p4_hosted_inbox_item item;
    uint8_t ssid[P4_HOSTED_ASSOCIATION_SSID_SIZE];
    uint8_t bssid[P4_HOSTED_ASSOCIATION_BSSID_SIZE];

    memset(&context, 0, sizeof context);
    memset(&test_resource, 0, sizeof test_resource);
    test_resource.associated = TRUE;
    wifi_resource_base = &test_resource;
    context.generation = 45u;
    CHECK(p4_hosted_link_init(&context.link_observation, 44u));
    fill_pattern(ssid, sizeof ssid, 0x35u);
    fill_pattern(bssid, sizeof bssid, 0x55u);
    CHECK(make_item(&item, 775u, 0, ssid, 32u, bssid));
    check_callback_refusal_unchanged(&context, &item);

    /* Other event metadata is counted without changing the typed ledger. */
    memset(&item, 0, sizeof item);
    item.msg_type = P4_HOSTED_RPC_TYPE_EVENT;
    item.msg_id = 769u;
    item.uid = 0u;
    CHECK(wifi_owner_event(&context, &item) == 1);
    CHECK(context.owner_events == 1u);
    CHECK(context.owner_last_event == 769u);
    CHECK(context.link_observation.generation == 44u);
    CHECK(context.link_observation.revision == 0u);
    CHECK(context.link_observation.kind == P4_HOSTED_LINK_NONE);
}

