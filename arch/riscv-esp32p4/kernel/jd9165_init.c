/*
 * The JD9165BA initialisation sequences for the 1024x600 7" panel of the
 * Guition JC1060P470C board, kept under their own licence.
 *
 * Like jd9365_init.c, this file is deliberately not AROS-licensed and
 * deliberately contains nothing else.  The command values below are the board
 * vendor's, copied byte for byte from its ESP-IDF demos, and they are
 * panel-vendor data rather than an implementation: changing them would mean
 * asking the panel supplier, not reasoning about them.  The board comes with
 * two panel revisions that use different sequences, hence two tables.  The
 * SPDX lines above are the notices of the two source files, one per table.
 *
 * Sources, both below JC1060WP470C/1-Demo/Demo_IDF/ESP-IDF_5.5.4/:
 *
 *   krnP4JD9165InitOld, 51 commands
 *     JC1060P470C_I_W_Y_Old_Panel/common_components/
 *     esp32_p4_function_ev_board/esp32_p4_function_ev_board.c,
 *     lcd_cmd[], lines 520-583.
 *
 *   krnP4JD9165InitNew, 60 commands
 *     JC1060P470C_I_W_Y_New_Panel/common_components/
 *     espressif__esp32_p4_function_ev_board/esp32_p4_function_ev_board.c,
 *     lcd_cmd[], lines 404-466.
 *
 * The Arduino copies of the same two tables (Demo_Arduino/<same board
 * directory>/lvgl_demo_v8/src/lcd/esp_lcd_jd9165.c, lines 119-182 for the old
 * panel and 119-181 for the new one) were compared with these.  Every
 * command, parameter, length and delay is identical.
 *
 * What the tables do not contain.  The vendor driver (panel_jd9165_init in
 * esp_lcd_jd9165.c) first reads the controller ID with DCS 0x04 (three
 * bytes), then sends MADCTL 0x36 with 0x00 (RGB element order), and only then
 * walks the table.  Here the caller does both before it sends the table; they
 * are not part of it.
 */

